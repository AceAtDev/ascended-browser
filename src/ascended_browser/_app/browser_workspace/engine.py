class ElectronEmbeddedEngine(WorkspaceBrowserEngine):
    """Chromium guests rendered inside the Ascended desktop app.

    Contract: docs/desktop/ARCHITECTURE.md § Embedded browser. The browser
    runs on the user's desktop; this engine reaches it through the loopback
    relay ``/api/desktop/cdp/<token>`` (routes/desktop_routes.py), which pipes
    CDP to the owner's connected desktop browser host. There is no local
    process, display, profile directory, fingerprint or proxy: the backend
    skips those steps when ``embedded`` is true.
    """

    engine_id = "electron-chromium"
    embedded = True
    presentation = "embedded"

    def __init__(self, owner: str) -> None:
        self.owner = owner or ""
        # id(page) -> (page, {"guest_key", "target_id"}); dropped on close.
        self._identities: dict[int, tuple[Any, dict[str, str]]] = {}
        self._identify_tasks: set[Any] = set()

    @property
    def capabilities(self) -> dict[str, Any]:
        try:
            from ascended_browser.runtime.desktop import desktop_host_status

            supported = bool(desktop_host_status(self.owner).get("use_for_agent"))
        except Exception:
            supported = False
        return {
            "engine": self.engine_id,
            "presentation": self.presentation,
            "supported": supported,
            "display_capture": False,
            "persistent_profile": False,
        }

    def launch_options(
        self, *, profile: Path | None = None, fingerprint: Any = None, display: str = "",
        xauthority: str = "", proxy: str = "", dynamic_viewport: bool = False,
        audio_sink: str = "",
    ) -> dict[str, Any]:
        return {"owner": self.owner}

    def context_manager(self, launch_options: dict[str, Any]) -> Any:
        return _ElectronCdpContext(str(launch_options.get("owner", self.owner) or ""))

    async def prepare_user_control(self, page: Any) -> None:
        # The user sees and drives the guest directly; no window to raise.
        return None

    async def create_page(self, context: Any) -> Any:
        page = await context.new_page()
        await self.identify(page)
        return page

    def identity(self, page: Any) -> dict[str, str]:
        entry = self._identities.get(id(page))
        return dict(entry[1]) if entry is not None and entry[0] is page else {}

    async def identify(self, page: Any) -> dict[str, str]:
        """Read which desktop <webview> renders this page (gateway guestKey).

        The gateway answers Target.getTargetInfo on a page session itself and
        adds the shell's ``guestKey``. Failure leaves the page without an
        identity; the UI then falls back to URL matching.
        """
        existing = self.identity(page)
        if existing:
            return existing
        try:
            session = await page.context.new_cdp_session(page)
            try:
                info = (await session.send("Target.getTargetInfo")).get("targetInfo") or {}
            finally:
                try:
                    await session.detach()
                except Exception:
                    pass
        except Exception:
            log.debug("Could not identify desktop browser page", exc_info=True)
            return {}
        identity = {
            "guest_key": str(info.get("guestKey") or ""),
            "target_id": str(info.get("targetId") or ""),
        }
        key = id(page)
        self._identities[key] = (page, identity)
        try:
            page.once("close", lambda _page=None, key=key: self._identities.pop(key, None))
        except Exception:
            pass
        return dict(identity)

    def identify_soon(self, page: Any) -> None:
        import asyncio

        try:
            task = asyncio.get_running_loop().create_task(self.identify(page))
        except RuntimeError:
            return
        self._identify_tasks.add(task)
        task.add_done_callback(self._identify_tasks.discard)


class _ElectronCdpContext:
    """Async context manager yielding the desktop's default BrowserContext."""

    def __init__(self, owner: str) -> None:
        self.owner = owner
        self._playwright: Any = None
        self._browser: Any = None

    async def __aenter__(self) -> Any:
        # Imported lazily: the token API lives with the desktop routes and is
        # in-process only (never an env var a tool could inherit).
        from playwright.async_api import async_playwright
        from ascended_browser.runtime.desktop import DesktopBrowserUnavailable, mint_cdp_token

        endpoint = mint_cdp_token(self.owner)  # raises DesktopBrowserUnavailable
        _driver_env_with_compile_cache()
        self._playwright = await async_playwright().start()
        try:
            self._browser = await self._playwright.chromium.connect_over_cdp(endpoint, timeout=20_000)
            if not self._browser.contexts:
                raise DesktopBrowserUnavailable("The desktop browser exposed no browser context")
            return self._browser.contexts[0]
        except BaseException:
            await self._stop()
            raise

    async def __aexit__(self, *exc_info: Any) -> None:
        await self._stop()

    async def _stop(self) -> None:
        browser, self._browser = self._browser, None
        playwright, self._playwright = self._playwright, None
        if browser is not None:
            try:
                # For a CDP connection this closes the transport only; the
                # desktop then closes the guests that belonged to it.
                await browser.close()
            except Exception:
                pass
        if playwright is not None:
            try:
                await playwright.stop()
            except Exception:
                pass


def desktop_engine_for_owner(owner: str) -> ElectronEmbeddedEngine | None:
    """The embedded engine when this owner's desktop host offers it, else None."""
    try:
        from ascended_browser.runtime.desktop import desktop_host_status

        status = desktop_host_status(owner or "")
    except Exception:
        return None
    if status.get("use_for_agent"):
        return ElectronEmbeddedEngine(owner or "")
    return None


def desktop_host_absent_for(owner: str) -> float:
    try:
        from ascended_browser.runtime.desktop import desktop_host_absent_for as _absent

        return float(_absent(owner or ""))
    except Exception:
        return 0.0


def desktop_host_connected(owner: str) -> bool:
    try:
        from ascended_browser.runtime.desktop import desktop_host_status

        return bool(desktop_host_status(owner or "").get("connected"))
    except Exception:
        return False
